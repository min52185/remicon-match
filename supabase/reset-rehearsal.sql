-- 리허설 초기화 — 지난 주문·배송 자국만 지운다
--
-- 마이그레이션이 아니다. 번호를 안 붙인 이유 — 스키마를 바꾸지 않고, 필요할 때만
-- 손으로 돌리는 도구다. 리허설을 다시 하기 전이나 발표 직전에 쓴다.
--
-- 지우는 것   주문 · 배송 · AI 배분 계획 · GPS 기록
-- 남기는 것   회사 · 현장 · 공장 · 차량 · 계정
--
-- 공장의 출하 가능 차량·물량도 시드 값으로 되돌린다. 리허설을 돌리면 출하할
-- 때마다 줄어들어서, 그대로 두면 다음 리허설에서 "출하 여력 없음" 이 뜬다.
--
-- ⚠ 되돌릴 수 없다. 발표 자료로 쓸 납품서가 있으면 먼저 인쇄해 두자.
--
-- 실행: Supabase SQL Editor 에 전체 붙여넣고 Run.
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 1. 리허설 자국 지우기
--
-- 순서가 중요하다. 배송이 주문을 참조하고, GPS 가 배송을 참조한다.
-- (외래키에 cascade 가 걸려 있어 한 번에 지워지기도 하지만, 무엇이 지워지는지
--  눈에 보이는 편이 낫다.)
-- ---------------------------------------------------------------------------

delete from truck_locations;
delete from deliveries;
delete from orders;
delete from plan_items;
delete from allocation_plans;


-- ---------------------------------------------------------------------------
-- 2. 공장 출하 현황을 시드 값으로 되돌리기
--
-- 0002_seed.sql 과 같은 값이다. 세 곳은 일부러 특이하게 둔 것이라 그대로 살린다.
--   03번  차량이 전부 출하 중 (0대)
--   04번  물량 부족 (36m³)
--   06번  출하 중지
-- AI 배분이 "왜 이 공장은 빠졌나" 를 보여 주려면 이런 공장이 있어야 한다.
-- ---------------------------------------------------------------------------

update plant_status s set
  available_trucks = v.trucks,
  available_volume = v.volume,
  is_open          = v.open,
  updated_at       = now()
from (values
  ('70000000-0000-4000-8000-000000000001'::uuid,  8, 240.0, true),
  ('70000000-0000-4000-8000-000000000002'::uuid,  5, 150.0, true),
  ('70000000-0000-4000-8000-000000000003'::uuid,  0,   0.0, true),
  ('70000000-0000-4000-8000-000000000004'::uuid,  3,  36.0, true),
  ('70000000-0000-4000-8000-000000000005'::uuid, 10, 320.0, true),
  ('70000000-0000-4000-8000-000000000006'::uuid,  4,  90.0, false),
  ('70000000-0000-4000-8000-000000000007'::uuid,  9, 300.0, true),
  ('70000000-0000-4000-8000-000000000008'::uuid,  6, 180.0, true),
  ('70000000-0000-4000-8000-000000000009'::uuid,  7, 200.0, true),
  ('70000000-0000-4000-8000-00000000000a'::uuid,  4, 120.0, true),
  ('70000000-0000-4000-8000-00000000000b'::uuid,  5, 150.0, true),
  ('70000000-0000-4000-8000-00000000000c'::uuid,  6, 200.0, true)
) as v(plant_id, trucks, volume, open)
where s.plant_id = v.plant_id;


-- ---------------------------------------------------------------------------
-- 3. 확인
-- ---------------------------------------------------------------------------

select
  (select count(*) from orders)           as 주문,
  (select count(*) from deliveries)       as 배송,
  (select count(*) from allocation_plans) as 배분계획,
  (select count(*) from truck_locations)  as GPS기록,
  (select count(*) from sites)            as 현장_남음,
  (select count(*) from plants)           as 공장_남음,
  (select count(*) from trucks)           as 차량_남음;


