-- 회사를 늘리고, 가입하면서 직접 만들 수 있게 한다.
--
-- 시드에 건설사가 '한빛건설' 하나뿐이라 가입한 사람이 전부 그 한 회사로 몰렸다.
-- 그러면 같은 건설사 안에서 현장 목록이 서로 보이는 터라, 0010 으로 좁힌 효과가
-- 반쯤 사라진다. 회사를 나누는 것이 현장을 나누는 것만큼 중요하다.
--
-- 두 가지를 한다.
--   1. 건설사를 몇 곳 더 넣는다 (전부 가상 회사다 — 실제 업체와 무관)
--   2. 가입한 사람이 자기 회사를 직접 만들 수 있게 한다. 목록에 없는 회사면
--      지금까지는 아무 회사나 고르는 수밖에 없었다.

-- ──────────────────────────────────────────────────────────────
-- 1. 회사 더 넣기
--
-- id 를 고정해 두는 이유: 이 파일을 두 번 돌려도 중복이 생기지 않게 하려고.
-- on conflict do nothing 과 짝이다.
-- ──────────────────────────────────────────────────────────────

insert into companies (id, name, kind) values
  ('c0000000-0000-4000-8000-000000000101', '대진종합건설', '건설사'),
  ('c0000000-0000-4000-8000-000000000102', '서해건설',     '건설사'),
  ('c0000000-0000-4000-8000-000000000103', '미래엔건설',   '건설사'),
  ('c0000000-0000-4000-8000-000000000104', '한솔이엔씨',   '건설사'),
  ('c0000000-0000-4000-8000-000000000105', '동방건설',     '건설사'),
  ('c0000000-0000-4000-8000-000000000106', '정우개발',     '건설사'),
  ('c0000000-0000-4000-8000-000000000107', '세움건설',     '건설사'),
  ('c0000000-0000-4000-8000-000000000108', '나래건설',     '건설사')
on conflict (id) do nothing;

-- ──────────────────────────────────────────────────────────────
-- 2. 가입하면서 회사 만들기
--
-- 역할과 종류를 맞춘다. 현장 계정이 레미콘사를 만들거나 그 반대가 되면
-- 가입 화면의 목록이 어그러진다 (현장은 건설사만, 공장·기사는 레미콘사만 고른다).
--
-- 아무나 만들 수 있어도 되는 이유: 회사 줄 자체에는 이름과 종류밖에 없다.
-- 실제 자료는 현장·공장에 붙어 있고 그쪽은 0010 과 0001 이 막는다.
-- ──────────────────────────────────────────────────────────────

drop policy if exists "역할에 맞는 회사를 만든다" on companies;
create policy "역할에 맞는 회사를 만든다" on companies for insert to authenticated
  with check (
    (my_role() = 'site' and kind = '건설사')
    or (my_role() in ('plant', 'driver') and kind = '레미콘사')
  );

-- 같은 이름이 쌓이지 않게 한다. 대소문자·앞뒤 공백은 같은 이름으로 본다.
create unique index if not exists companies_name_kind_uniq
  on companies (lower(btrim(name)), kind);

-- ──────────────────────────────────────────────────────────────
-- 3. 확인
-- ──────────────────────────────────────────────────────────────

select kind as 종류, count(*) as 회사수
from companies
group by kind
order by kind;
