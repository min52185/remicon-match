-- 확인 — 실행 후 아래 숫자가 나오면 성공
--   회사 13 / 현장 3 / 공장 12 / 출하현황 12 / 차량 139
-- ---------------------------------------------------------------------------

select
  (select count(*) from companies)    as 회사,
  (select count(*) from sites)        as 현장,
  (select count(*) from plants)       as 공장,
  (select count(*) from plant_status) as 출하현황,
  (select count(*) from trucks)       as 차량;
