-- ---------------------------------------------------------------------------
-- 5. 차량 — 공장별 보유 대수만큼 자동 생성 (총 139대)
--   차량번호는 공장·호차에서 결정적으로 만든다(다시 실행해도 같은 번호).
-- ---------------------------------------------------------------------------

insert into trucks (plant_id, no, plate_no, capacity_m3)
select
  p.id,
  g.n,
  '경기 ' || (80 + ((p.fleet_size * 7 + g.n * 3) % 20))::text
           || '바 ' || (1000 + ((p.fleet_size * 977 + g.n * 1319) % 9000))::text,
  6
from plants p
cross join lateral generate_series(1, p.fleet_size) as g(n)
on conflict (plant_id, no) do nothing;

