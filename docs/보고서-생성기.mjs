const M = 50;
const W = 595.28 - M * 2;

const doc = new PDFDocument({ size: 'A4', margin: M, bufferPages: true });
doc.pipe(fs.createWriteStream(OUT));
doc.registerFont('kr', 'C:/Windows/Fonts/malgun.ttf');
doc.registerFont('krb', 'C:/Windows/Fonts/malgunbd.ttf');

const body = () => {
  doc.x = M;
  return doc.font('kr').fontSize(9.5).fillColor(C.dark);
};

function need(h) {
  if (doc.y + h > doc.page.height - M - 24) doc.addPage();
}

function h1(t, sub) {
  need(60);
  doc.moveDown(0.8);
  doc.font('krb').fontSize(15).fillColor(C.dark).text(t);
  doc
    .moveTo(M, doc.y + 4)
    .lineTo(M + W, doc.y + 4)
    .lineWidth(1.4)
    .strokeColor(C.rust)
    .stroke();
  doc.moveDown(0.6);
  if (sub) {
    doc.font('kr').fontSize(9).fillColor(C.wet).text(sub, { width: W });
    doc.moveDown(0.4);
  }
  body();
}

function h2(t) {
  need(34);
  doc.moveDown(0.5);
  doc.font('krb').fontSize(11).fillColor(C.rust).text(t);
  doc.moveDown(0.3);
  body();
}

function p(t, opt = {}) {
  need(26);
  body().text(t, { width: W, lineGap: 2.2, ...opt });
  doc.moveDown(0.35);
}

function bullets(items) {
  for (const it of items) {
    need(20);
    const x = doc.x;
    body().text('·', x + 4, doc.y, { continued: false, width: 10 });
    doc.moveUp(1);
    body().text(String(it), x + 16, doc.y, { width: W - 16, lineGap: 2 });
    doc.x = M;
    doc.moveDown(0.15);
  }
  doc.x = M;
  doc.moveDown(0.25);
}

/** cols: [{w, label}] · rows: [[cell...]] · cell: string | {t, c, b} */
function table(cols, rows, { head = true, zebra = true } = {}) {
  const pad = 5;
  const drawHead = () => {
    const hh = 19;
    need(hh + 20);
    const y = doc.y;
    doc.rect(M, y, W, hh).fillColor(C.dark).fill();
    let x = M;
    cols.forEach((c) => {
      doc
        .font('krb')
        .fontSize(8.5)
        .fillColor('#FFFFFF')
        .text(c.label, x + pad, y + 5.5, { width: c.w - pad * 2 });
      x += c.w;
    });
    doc.y = y + hh;
  };

  if (head) drawHead();

  rows.forEach((row, i) => {
    const cells = row.map((c) => (typeof c === 'string' ? { t: c } : c));
    const hs = cells.map((c, j) =>
      doc
        .font(c.b ? 'krb' : 'kr')
        .fontSize(8.5)
        .heightOfString(c.t, { width: cols[j].w - pad * 2, lineGap: 1.5 }),
    );
    const rh = Math.max(...hs) + pad * 2;

    if (doc.y + rh > doc.page.height - M - 24) {
      doc.addPage();
      if (head) drawHead();
    }

    const y = doc.y;
    if (zebra && i % 2 === 1) doc.rect(M, y, W, rh).fillColor(C.paper).fill();

    let x = M;
    cells.forEach((c, j) => {
      doc
        .font(c.b ? 'krb' : 'kr')
        .fontSize(8.5)
        .fillColor(c.c || C.dark)
        .text(c.t, x + pad, y + pad, { width: cols[j].w - pad * 2, lineGap: 1.5 });
      x += cols[j].w;
    });

    doc
      .moveTo(M, y + rh)
      .lineTo(M + W, y + rh)
      .lineWidth(0.5)
      .strokeColor(C.line)
      .stroke();
    doc.y = y + rh;
  });

  doc.x = M;
  doc.moveDown(0.7);
  body();
}

