const body = () => {
  doc.x = M;
  return doc.font('kr').fontSize(9.5).fillColor(C.dark);
};

function need(h) {
  if (doc.y + h > doc.page.height - M - 26) doc.addPage();
}

function h1(t, sub) {
  doc.addPage();
  doc.font('krb').fontSize(17).fillColor(C.dark).text(t);
  doc
    .moveTo(M, doc.y + 5)
    .lineTo(M + W, doc.y + 5)
    .lineWidth(1.6)
    .strokeColor(C.rust)
    .stroke();
  doc.moveDown(0.7);
  if (sub) {
    doc.font('kr').fontSize(9).fillColor(C.wet).text(sub, { width: W });
    doc.moveDown(0.4);
  }
  body();
}

function h2(t) {
  need(36);
  doc.moveDown(0.6);
  doc.font('krb').fontSize(11.5).fillColor(C.rust).text(t, { width: W });
  doc.moveDown(0.35);
  body();
}

/** 역할 칩 + 제목 */
function step(roleKey, t) {
  need(40);
  doc.moveDown(0.55);
  const r = ROLE[roleKey];
  const y = doc.y;

  const chipW = 38;
  const chipH = 14;
  doc.roundedRect(M, y, chipW, chipH, 3).fillColor(r.color).fill();
  doc
    .font('krb')
    .fontSize(8)
    .fillColor('#FFFFFF')
    .text(r.label, M, y + 3, { width: chipW, align: 'center' });

  doc
    .font('krb')
    .fontSize(11)
    .fillColor(C.dark)
    .text(t, M + chipW + 8, y + 1, { width: W - chipW - 8 });

  doc.y = Math.max(doc.y, y + chipH) + 4;
  body();
}

function p(t, opt = {}) {
  need(26);
  body().text(t, { width: W, lineGap: 2.2, ...opt });
  doc.moveDown(0.35);
}

/** 번호 매긴 '할 일' */
function steps(items) {
  for (let i = 0; i < items.length; i++) {
    need(20);
    const x = doc.x;
    doc
      .font('krb')
      .fontSize(9)
      .fillColor(C.rust)
      .text(String(i + 1), x + 2, doc.y, { width: 14 });
    doc.moveUp(1);
    body().text(String(items[i]), x + 18, doc.y, { width: W - 18, lineGap: 2 });
    doc.x = M;
    doc.moveDown(0.15);
  }
  doc.x = M;
  doc.moveDown(0.3);
}

function bullets(items) {
  for (const it of items) {
    need(20);
    const x = doc.x;
    body().text('·', x + 4, doc.y, { width: 10 });
    doc.moveUp(1);
    body().text(String(it), x + 16, doc.y, { width: W - 16, lineGap: 2 });
    doc.x = M;
    doc.moveDown(0.15);
  }
  doc.x = M;
  doc.moveDown(0.3);
}

/** 할 말 — 왼쪽에 세로선을 두고 안쪽으로 */
function say(lines) {
  const arr = Array.isArray(lines) ? lines : [lines];
  need(34);
  const top = doc.y + 2;

  doc.x = M + 14;
  for (const l of arr) {
    doc.font('kr').fontSize(9.5).fillColor(C.wet).text(`“${l}”`, { width: W - 18, lineGap: 3 });
    doc.moveDown(0.25);
  }

  doc
    .moveTo(M + 3, top)
    .lineTo(M + 3, doc.y)
    .lineWidth(2)
    .strokeColor(C.rust)
    .stroke();

  doc.x = M;
  doc.moveDown(0.4);
  body();
}

/** 상태 한 줄 — ok / warn / bad */
function note(kind, t) {
  const color = kind === 'ok' ? C.ok : kind === 'bad' ? C.bad : C.warn;
  const mark = kind === 'ok' ? '✓' : '!';
  need(26);
  const top = doc.y;

  doc.x = M + 16;
  doc.font('kr').fontSize(9).fillColor(color).text(t, { width: W - 20, lineGap: 2 });

  doc
    .font('krb')
    .fontSize(10)
    .fillColor(color)
    .text(mark, M + 3, top, { width: 12 });

  doc.x = M;
  doc.y = Math.max(doc.y, top + 12);
  doc.moveDown(0.35);
  body();
}

/** cols: [{w,label}] · rows: [[cell]] · cell: string | {t,c,b} */
function table(cols, rows, { head = true } = {}) {
  const pad = 5;
  const drawHead = () => {
    const hh = 18;
    need(hh + 20);
    const y = doc.y;
    doc.rect(M, y, W, hh).fillColor(C.dark).fill();
    let x = M;
    cols.forEach((c) => {
      doc
        .font('krb')
        .fontSize(8.5)
        .fillColor('#FFFFFF')
        .text(c.label, x + pad, y + 5, { width: c.w - pad * 2 });
      x += c.w;
    });
    doc.y = y + hh;
  };

  if (head) drawHead();

  rows.forEach((row, i) => {
    const cells = row.map((c) => (typeof c === 'string' ? { t: c } : c));
    const hs = cells.map((c, j) =>
      doc
        .font(c.b ? 'krb' : 'kr')
        .fontSize(8.5)
        .heightOfString(c.t, { width: cols[j].w - pad * 2, lineGap: 1.5 }),
    );
    const rh = Math.max(...hs) + pad * 2;

    if (doc.y + rh > doc.page.height - M - 26) {
      doc.addPage();
      if (head) drawHead();
    }

    const y = doc.y;
    if (i % 2 === 1) doc.rect(M, y, W, rh).fillColor(C.paper).fill();

    let x = M;
    cells.forEach((c, j) => {
      doc
        .font(c.b ? 'krb' : 'kr')
        .fontSize(8.5)
        .fillColor(c.c || C.dark)
        .text(c.t, x + pad, y + pad, { width: cols[j].w - pad * 2, lineGap: 1.5 });
      x += cols[j].w;
    });

    doc
      .moveTo(M, y + rh)
      .lineTo(M + W, y + rh)
      .lineWidth(0.5)
      .strokeColor(C.line)
      .stroke();
    doc.y = y + rh;
  });

  doc.x = M;
  doc.moveDown(0.6);
  body();
}

